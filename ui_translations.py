for _index, _code in enumerate(tuple(LANGUAGES)[1:]):
    CATALOGS[_code] = {source: translations[_index] for source, translations in TRANSLATIONS.items()}


def translate(text: str, language: str) -> str:
    catalogue = CATALOGS[language]
    if text in catalogue:
        return catalogue[text]
    numbered = re.fullmatch(r"(\d+\.\s+)(.+)", text)
    if numbered and numbered[2] in catalogue:
        return numbered[1] + catalogue[numbered[2]]
    return text


def instructions(language: str) -> str:
    first, second = EXAMPLES[language]
    steps = [
        "Source SRT (to synchronize)", "Processing device", "Hearing-impaired filter",
        "Select matching cues...", "Save synchronized SRT", "Analyze and synchronize",
    ]
    workflow = "\n".join("- " + translate(step, language) for step in steps)
    return (
        first + "\n- " + translate("Reference SRT (optional)", language) + "\n" + workflow
        + "\n\n" + second + "\n" + workflow
    )
